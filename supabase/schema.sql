-- ============================================================================
-- WORKBRIDGE — Supabase schema, Row Level Security and storage policies
-- ----------------------------------------------------------------------------
-- Run this whole file once in the Supabase SQL Editor (or `psql`) on a new
-- project. It is idempotent and safe to re-run while developing.
--
-- ROW CONTRACT
--   Every collection table stores one application record per row:
--       id  text primary key
--       doc jsonb not null        -- the record itself
--   server/supabase.js reads `select=id,doc` and upserts `{ id, doc }`.
--   Generated columns expose the fields that indexes and policies need
--   (role, status, owner ids, currency) without changing the adapter.
--
-- SECURITY MODEL
--   * RLS is enabled on every table and every table has explicit policies.
--   * The browser never receives a Supabase key. All traffic goes through the
--     WORKBRIDGE server, which uses the service-role key server-side only.
--   * Policies therefore act as defence in depth: even a leaked anon key cannot
--     read another user's rows, because access requires an authenticated JWT
--     whose auth.uid() maps to a row in public.users.
--   * Institutional addresses and contact details are never exposed publicly.
--     The only public surface is the public.institution_directory view
--     (approved name + type).
--   * Agreements, invoices and signatures live in private storage buckets and
--     are served through short-lived signed URLs generated by the server.
-- ============================================================================

create extension if not exists "pgcrypto";

-- ------------------------------------------------------------------ helpers --
-- auth.uid() is the Supabase Auth user; public.users.id is the application id.

create or replace function public.app_user_id()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select id from public.users where auth_id = auth.uid()::text limit 1;
$$;

create or replace function public.app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select doc->>'role' from public.users where id = public.app_user_id()),
    'anon'
  );
$$;

create or replace function public.app_status()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select doc->>'status' from public.users where id = public.app_user_id()),
    'anon'
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.app_role() = 'admin' and public.app_status() = 'active';
$$;

-- Does the current user own the listing this row refers to?
create or replace function public.owns_job(p_job_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.jobs
    where id = p_job_id and doc->>'business_id' = public.app_user_id()
  );
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

