-- commissions: administrator-only ledger. The server writes one row each time
-- an agreement or invoice is created while commission is enabled, freezing the
-- percentage used at that moment. No client policy is granted: only the server
-- (service role) reads it, and an invoice never carries commission data.
create table if not exists public.commissions (
  id          text primary key,
  doc         jsonb not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  doc_type    text generated always as (doc->>'doc_type') stored,
  currency    text generated always as (doc->>'currency') stored
);

alter table public.commissions enable row level security;

drop policy if exists commissions_admin_read on public.commissions;
create policy commissions_admin_read on public.commissions
  for select to authenticated
  using (public.is_admin());

-- ------------------------------------------------- public institution list ---
-- The only public institutional surface: approved names and types.
-- Addresses, phones and contact people are never selected here.

create or replace view public.institution_directory as
  select
    id,
    doc->>'name' as name,
    doc->>'type' as type
  from public.institutions
  where doc->>'status' = 'approved';

grant select on public.institution_directory to anon, authenticated;

-- ---------------------------------------------------------------- storage ---
-- Private buckets for generated PDFs. Clients never read these directly: the
-- server creates short-lived signed URLs for the two parties only.

insert into storage.buckets (id, name, public)
values ('agreements', 'agreements', false)
on conflict (id) do nothing;

insert into storage.buckets (id, name, public)
values ('invoices', 'invoices', false)
on conflict (id) do nothing;

-- No storage.objects policies are created for anon/authenticated on purpose:
-- without a policy, RLS denies direct access. The service role used by the
-- server bypasses RLS and issues signed URLs.

-- ------------------------------------------------------------------ grants ---
-- Least privilege: the API talks to Postgres through the service role, so the
-- anon/authenticated roles only need what the policies above allow.

revoke all on public.password_reset_tokens from anon, authenticated;
grant select on public.institution_directory to anon, authenticated;

-- ---------------------------------------------------------------- privileges --
-- The SQL editor runs as `postgres`, and tables created here are not readable
-- by the API roles by default. That is why the server logged
--   supabase_403: permission denied for table users   (Postgres error 42501)
-- even with a correct service-role key. The grants below fix it. Row Level
-- Security above still decides what an end user may see; the service role is
-- only ever used server-side, never in the browser.

grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;

-- Keep future tables created in this schema usable without re-running the file.
alter default privileges in schema public grant all on tables to service_role;
alter default privileges in schema public grant all on sequences to service_role;
