-- ----------------------------------------------------------- updated_at -----

do $$
declare
  t text;
begin
  foreach t in array array[
    'users', 'worker_profiles', 'business_profiles', 'institutions', 'jobs',
    'applications', 'agreements', 'invoices', 'notifications', 'reports',
    'password_reset_tokens', 'audit_log', 'payments'
  ]
  loop
    execute format('drop trigger if exists %I_touch on public.%I', t, t);
    execute format(
      'create trigger %I_touch before update on public.%I
         for each row execute function public.touch_updated_at()', t, t
    );
  end loop;
end $$;

-- ---------------------------------------------------------------------- RLS --

do $$
declare
  t text;
begin
  foreach t in array array[
    'users', 'worker_profiles', 'business_profiles', 'institutions', 'jobs',
    'applications', 'agreements', 'invoices', 'notifications', 'reports',
    'password_reset_tokens', 'audit_log', 'payments', 'app_settings'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
  end loop;
end $$;

-- users: read yourself, admins read everyone. Role/status are never self-editable.
drop policy if exists users_select_self_or_admin on public.users;
create policy users_select_self_or_admin on public.users
  for select to authenticated
  using (id = public.app_user_id() or public.is_admin());

drop policy if exists users_update_self on public.users;
create policy users_update_self on public.users
  for update to authenticated
  using (id = public.app_user_id())
  with check (
    id = public.app_user_id()
    and doc->>'role' = public.app_role()
    and doc->>'status' = 'active'
  );

drop policy if exists users_admin_all on public.users;
create policy users_admin_all on public.users
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- worker_profiles: the worker owns the row; businesses may read active workers
-- (worker search); admins manage everything.
drop policy if exists worker_profiles_read on public.worker_profiles;
create policy worker_profiles_read on public.worker_profiles
  for select to authenticated
  using (
    user_id = public.app_user_id()
    or public.app_role() in ('business', 'admin')
  );

drop policy if exists worker_profiles_write on public.worker_profiles;
create policy worker_profiles_write on public.worker_profiles
  for insert to authenticated
  with check (user_id = public.app_user_id() and public.app_role() = 'worker');

drop policy if exists worker_profiles_update on public.worker_profiles;
create policy worker_profiles_update on public.worker_profiles
  for update to authenticated
  using (user_id = public.app_user_id() or public.is_admin())
  with check (user_id = public.app_user_id() or public.is_admin());

